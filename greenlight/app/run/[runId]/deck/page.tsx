"use client"

/**
 * Pre-Production Deck — rendered as a React page with embedded images.
 *
 * Access at /run/[runId]/deck?variant=ecd|client
 * Reads deck copy + Visual DNA from Firestore and renders the full deck.
 */

import { useEffect, useState } from "react"
import { useParams, useSearchParams } from "next/navigation"
import Link from "next/link"

// ── Types ──────────────────────────────────────────────────────────────────────

interface DeckCopyData {
  titleSlide: { headline: string; subtitle: string }
  briefSummary: string
  territories: Record<string, {
    coverHeadline: string
    propositionBlurb: string
    visualSummary: string
    toneDescriptor: string
    sceneArcNotes: string
    sceneCount: number
    flowPromptStyle: string
    riskFlag: string | null
  }>
  visualOverview: {
    summary: string
    paletteComparison: string
    cinematographyComparison: string
    ingredientComparison: string
  }
  brandAlignment: {
    territoryNotes: Record<string, string>
    divergenceNotes: string
    riskSummary: string
  }
  approvalSlide: {
    instructions: string
    territoryOptions: Array<{ id: string; name: string; summary: string }>
  }
  nextSteps: string
}

interface IngredientData {
  ingredient_id: string
  type: string
  description: string
  generated_reference_uri: string | null
  flow_ingredient_prompt: string
}

interface VisualDnaData {
  territory_id: string
  palette: { primary: string[]; accent: string[]; forbidden: string[] }
  ingredients: IngredientData[]
  cinematography: {
    style: string
    preferred_shot_types: string[]
    camera_movement: string
    lighting: string
    color_grade: string
  }
}

// ── Helpers ────────────────────────────────────────────────────────────────────

function imgUrl(uri: string | null): string | null {
  if (!uri) return null
  if (uri.startsWith("https://")) return uri
  if (uri.startsWith("gs://")) {
    const m = uri.match(/^gs:\/\/([^\/]+)\/(.+)$/)
    if (m) return `https://storage.googleapis.com/${m[1]}/${m[2]}`
  }
  return uri
}

// ── Slide Components ───────────────────────────────────────────────────────────

function Slide({ children, style }: { children: React.ReactNode; style?: React.CSSProperties }) {
  return (
    <div
      style={{
        minHeight: "100vh",
        padding: "80px 64px",
        display: "flex",
        flexDirection: "column",
        justifyContent: "center",
        borderBottom: "1px solid #1a1a1a",
        ...style,
      }}
    >
      {children}
    </div>
  )
}

function TitleSlide({ headline, subtitle, brand }: { headline: string; subtitle: string; brand: string }) {
  return (
    <Slide style={{ background: "linear-gradient(135deg, #1a1a2e 0%, #0a0a0a 100%)" }}>
      <h1 style={{ fontSize: "3rem", fontWeight: 700, marginBottom: 16 }}>{headline}</h1>
      <p style={{ fontSize: "1.25rem", color: "#888", marginBottom: 8 }}>
        {subtitle.split("\n").map((l, i) => <span key={i}>{l}<br /></span>)}
      </p>
      <p style={{ color: "#555", fontSize: "0.8rem", marginTop: 24 }}>{brand} &middot; Generated by Greenlight</p>
    </Slide>
  )
}

function BriefSlide({ summary }: { summary: string }) {
  return (
    <Slide>
      <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Brief Summary</h2>
      <p style={{ fontSize: "1.1rem", color: "#bbb", maxWidth: 800 }}>{summary}</p>
    </Slide>
  )
}

function TerritoryCoverSlide({ name, proposition, tone, index, riskFlag }: {
  name: string; proposition: string; tone: string; index: number; riskFlag: string | null
}) {
  const bg = index === 0 ? "#0d1117" : index === 1 ? "#111710" : "#170f11"
  return (
    <Slide style={{ background: bg }}>
      <h2 style={{ fontSize: "2.25rem", marginBottom: 12, color: "#fff" }}>Territory {index + 1}: {name}</h2>
      <p style={{ fontSize: "1.3rem", color: "#ccc", marginTop: 16, maxWidth: 700 }}>{proposition}</p>
      <p style={{ color: "#888", marginTop: 12 }}>Tone: {tone}</p>
      {riskFlag && (
        <div style={{ display: "inline-block", background: "#7c2d12", color: "#fbbf24", padding: "4px 12px", borderRadius: 4, fontSize: "0.85rem", marginTop: 16 }}>
          ⚠ {riskFlag}
        </div>
      )}
    </Slide>
  )
}

function TerritoryVisualSlide({ territory, vd }: { territory: DeckCopyData["territories"][string]; vd: VisualDnaData | null }) {
  return (
    <Slide>
      <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Visual Language — {territory.coverHeadline}</h2>
      <p style={{ fontSize: "1.1rem", color: "#bbb", maxWidth: 800 }}>{territory.visualSummary}</p>
      <p style={{ marginTop: 16, color: "#888" }}>Tone: {territory.toneDescriptor}</p>

      {vd && (
        <div style={{ marginTop: 24 }}>
          {/* Palette */}
          <div style={{ marginBottom: 20 }}>
            <h4 style={{ color: "#888", fontSize: "0.85rem", marginBottom: 8 }}>Palette</h4>
            <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
              {vd.palette.primary.map((hex) => (
                <span key={hex} style={{ display: "inline-flex", alignItems: "center", gap: 6, color: "#aaa", fontSize: "0.8rem" }}>
                  <span style={{ display: "inline-block", width: 28, height: 28, borderRadius: 4, border: "1px solid #333", background: hex }} />
                  {hex}
                </span>
              ))}
              {vd.palette.accent.map((hex) => (
                <span key={hex} style={{ display: "inline-flex", alignItems: "center", gap: 6, color: "#888", fontSize: "0.8rem" }}>
                  <span style={{ display: "inline-block", width: 28, height: 28, borderRadius: 4, border: "1px solid #333", background: hex }} />
                  {hex}
                </span>
              ))}
            </div>
          </div>

          {/* Cinematography */}
          <div style={{ marginBottom: 20 }}>
            <h4 style={{ color: "#888", fontSize: "0.85rem", marginBottom: 8 }}>Cinematography</h4>
            <div style={{ fontSize: "0.85rem", color: "#aaa", display: "grid", gridTemplateColumns: "1fr 1fr", gap: 8, maxWidth: 600 }}>
              <span>Style: {vd.cinematography.style}</span>
              <span>Movement: {vd.cinematography.camera_movement}</span>
              <span>Lighting: {vd.cinematography.lighting}</span>
              <span>Grade: {vd.cinematography.color_grade}</span>
              <span>Shots: {vd.cinematography.preferred_shot_types.join(", ")}</span>
            </div>
          </div>

          {/* Reference images */}
          {vd.ingredients.filter((i) => imgUrl(i.generated_reference_uri)).length > 0 && (
            <div>
              <h4 style={{ color: "#888", fontSize: "0.85rem", marginBottom: 12 }}>Reference Images</h4>
              <div style={{ display: "flex", gap: 16, flexWrap: "wrap" }}>
                {vd.ingredients.filter((i) => imgUrl(i.generated_reference_uri)).map((ing) => (
                  <div key={ing.ingredient_id} style={{ maxWidth: 240 }}>
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img
                      src={imgUrl(ing.generated_reference_uri)!}
                      alt={ing.description}
                      style={{ width: "100%", borderRadius: 8, border: "1px solid #333" }}
                    />
                    <p style={{ fontSize: "0.75rem", color: "#666", marginTop: 4 }}>{ing.ingredient_id} — {ing.type}</p>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </Slide>
  )
}

function TerritoryDetailsSlide({ territory, showRisk }: { territory: DeckCopyData["territories"][string]; showRisk: boolean }) {
  return (
    <Slide>
      <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Production Notes — {territory.coverHeadline}</h2>
      <div style={{ fontSize: "1rem", color: "#bbb", maxWidth: 800, display: "flex", flexDirection: "column", gap: 16 }}>
        <p><strong style={{ color: "#888" }}>Scene Arc:</strong> {territory.sceneArcNotes}</p>
        <p><strong style={{ color: "#888" }}>Suggested Scenes:</strong> {territory.sceneCount}</p>
        <p><strong style={{ color: "#888" }}>Flow Prompt Style:</strong> {territory.flowPromptStyle}</p>
        {showRisk && territory.riskFlag && (
          <div style={{ background: "#7c2d12", color: "#fbbf24", padding: "8px 16px", borderRadius: 4, fontSize: "0.9rem", marginTop: 8 }}>
            ⚠ Risk: {territory.riskFlag}
          </div>
        )}
      </div>
    </Slide>
  )
}

// ── Page ───────────────────────────────────────────────────────────────────────

export default function DeckPage() {
  const params = useParams<{ runId: string }>()
  const searchParams = useSearchParams()
  const runId = params?.runId ?? ""
  const variant = (searchParams.get("variant") ?? "ecd") as "ecd" | "client"
  const isEcd = variant === "ecd"

  const [deckCopy, setDeckCopy] = useState<DeckCopyData | null>(null)
  const [visualDnas, setVisualDnas] = useState<Record<string, VisualDnaData>>({})
  const [brand, setBrand] = useState("")
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    if (!runId) return
    async function load() {
      try {
        const res = await fetch(`/api/run/${runId}`)
        const data = await res.json()
        if (!res.ok) throw new Error(data.error ?? "Failed to load")

        const outputData = data.stages?.output_generation
        const deck = outputData?._deckCopy as DeckCopyData | undefined
        if (!deck) throw new Error("No deck data found. Run Generate Deck first.")

        setDeckCopy(deck)
        setBrand((data.stages?.brief_parsing?.brand as string) ?? "Unknown")

        // Load Visual DNA territories for images
        const vdData = data.stages?.visual_dna?.territories as Record<string, VisualDnaData> | undefined
        if (vdData) setVisualDnas(vdData)
      } catch (err) {
        setError(err instanceof Error ? err.message : "Failed to load deck")
      } finally {
        setLoading(false)
      }
    }
    load()
  }, [runId])

  if (loading) {
    return (
      <main style={{ background: "#0a0a0a", color: "#e0e0e0", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ color: "#555" }}>Loading deck…</p>
      </main>
    )
  }

  if (error || !deckCopy) {
    return (
      <main style={{ background: "#0a0a0a", color: "#e0e0e0", minHeight: "100vh", padding: 80 }}>
        <Link href={`/run/${runId}`} style={{ color: "#888", fontSize: "0.9rem" }}>← Back to pipeline</Link>
        <h1 style={{ marginTop: 40, color: "#ef4444" }}>Error</h1>
        <p style={{ color: "#fca5a5", marginTop: 12 }}>{error ?? "No deck data available"}</p>
      </main>
    )
  }

  const territoryKeys = Object.keys(deckCopy.territories)

  return (
    <main style={{ background: "#0a0a0a", color: "#e0e0e0", fontFamily: "system-ui, -apple-system, sans-serif", lineHeight: 1.6 }}>
      {/* Print styles */}
      <style>{`@media print { .deck-slide { page-break-after: always; min-height: auto !important; padding: 40px !important; } }`}</style>

      {/* Back link */}
      <div style={{ position: "fixed", top: 20, left: 20, zIndex: 100 }}>
        <Link href={`/run/${runId}`} style={{ color: "#555", fontSize: "0.8rem", textDecoration: "none" }}>
          ← Pipeline
        </Link>
      </div>

      {/* Variant toggle */}
      <div style={{ position: "fixed", top: 20, right: 20, zIndex: 100, display: "flex", gap: 8 }}>
        <Link
          href={`/run/${runId}/deck?variant=ecd`}
          style={{
            padding: "4px 12px", borderRadius: 4, fontSize: "0.75rem", textDecoration: "none",
            background: isEcd ? "#333" : "#111", color: isEcd ? "#fff" : "#666",
          }}
        >
          Internal (ECD)
        </Link>
        <Link
          href={`/run/${runId}/deck?variant=client`}
          style={{
            padding: "4px 12px", borderRadius: 4, fontSize: "0.75rem", textDecoration: "none",
            background: !isEcd ? "#333" : "#111", color: !isEcd ? "#fff" : "#666",
          }}
        >
          Client
        </Link>
      </div>

      {/* Slide 1: Title */}
      <div className="deck-slide">
        <TitleSlide headline={deckCopy.titleSlide.headline} subtitle={deckCopy.titleSlide.subtitle} brand={brand} />
      </div>

      {/* Slide 2: Brief Summary */}
      <div className="deck-slide">
        <BriefSlide summary={deckCopy.briefSummary} />
      </div>

      {/* Slides 3-11: Territories (3 slides each) */}
      {territoryKeys.map((tid, i) => {
        const t = deckCopy.territories[tid]
        if (!t) return null
        const vd = visualDnas[tid] ?? null
        return (
          <div key={tid}>
            <div className="deck-slide">
              <TerritoryCoverSlide name={t.coverHeadline} proposition={t.propositionBlurb} tone={t.toneDescriptor} index={i} riskFlag={isEcd ? t.riskFlag : null} />
            </div>
            <div className="deck-slide">
              <TerritoryVisualSlide territory={t} vd={vd} />
            </div>
            <div className="deck-slide">
              <TerritoryDetailsSlide territory={t} showRisk={isEcd} />
            </div>
          </div>
        )
      })}

      {/* Slide 12: Visual DNA Overview */}
      <div className="deck-slide">
        <Slide>
          <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Visual DNA Overview</h2>
          <div style={{ fontSize: "1rem", color: "#bbb", maxWidth: 800, display: "flex", flexDirection: "column", gap: 16 }}>
            <p>{deckCopy.visualOverview.summary}</p>
            <p><strong style={{ color: "#888" }}>Palettes:</strong> {deckCopy.visualOverview.paletteComparison}</p>
            <p><strong style={{ color: "#888" }}>Cinematography:</strong> {deckCopy.visualOverview.cinematographyComparison}</p>
            <p><strong style={{ color: "#888" }}>Ingredients:</strong> {deckCopy.visualOverview.ingredientComparison}</p>
          </div>
        </Slide>
      </div>

      {/* Slide 13: Brand Alignment (ECD only) */}
      {isEcd && (
        <div className="deck-slide">
          <Slide style={{ borderLeft: "3px solid #7c2d12" }}>
            <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>
              Brand Alignment <span style={{ color: "#7c2d12", fontSize: "0.85rem" }}>🔒 Internal</span>
            </h2>
            <div style={{ fontSize: "1rem", color: "#bbb", maxWidth: 800, display: "flex", flexDirection: "column", gap: 12 }}>
              {Object.entries(deckCopy.brandAlignment.territoryNotes).map(([tid, note]) => (
                <p key={tid}><strong style={{ color: "#888" }}>{tid}:</strong> {note}</p>
              ))}
              <p style={{ marginTop: 16 }}><strong style={{ color: "#888" }}>Divergence:</strong> {deckCopy.brandAlignment.divergenceNotes}</p>
              <p><strong style={{ color: "#888" }}>Risk Summary:</strong> {deckCopy.brandAlignment.riskSummary}</p>
            </div>
          </Slide>
        </div>
      )}

      {/* Slide 14: Approval */}
      <div className="deck-slide">
        <Slide>
          <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Approval</h2>
          <p style={{ fontSize: "1.1rem", color: "#bbb", marginBottom: 32 }}>{deckCopy.approvalSlide.instructions}</p>
          <div style={{ display: "flex", flexDirection: "column", gap: 16, maxWidth: 700 }}>
            {deckCopy.approvalSlide.territoryOptions.map((opt) => (
              <div key={opt.id} style={{ padding: 20, border: "1px solid #333", borderRadius: 8, background: "#111" }}>
                <strong style={{ color: "#fff", fontSize: "1.15rem" }}>{opt.name}</strong>
                <span style={{ color: "#555", marginLeft: 8 }}>({opt.id})</span>
                <p style={{ color: "#888", marginTop: 4 }}>{opt.summary}</p>
              </div>
            ))}
          </div>
        </Slide>
      </div>

      {/* Slide 15: Next Steps */}
      <div className="deck-slide">
        <Slide>
          <h2 style={{ fontSize: "2rem", fontWeight: 600, marginBottom: 24, color: "#fff" }}>Next Steps</h2>
          <p style={{ fontSize: "1.1rem", color: "#bbb", maxWidth: 800 }}>{deckCopy.nextSteps}</p>
        </Slide>
      </div>

      {/* Footer */}
      <div style={{ textAlign: "center", color: "#555", fontSize: "0.85rem", padding: 40 }}>
        <p>{brand} &middot; Greenlight v0.1 &middot; {isEcd ? "ECD Internal Deck" : "Client Deck"}</p>
      </div>
    </main>
  )
}
