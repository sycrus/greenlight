/**
 * HTML Deck generator — renders the pre-production deck as a standalone
 * HTML page viewable in any browser. Bypasses the service account Drive
 * quota issue that blocks Slides API usage in personal GCP projects.
 */

import type { DeckCopy } from "@greenlight/lib/types/pipeline"

export function generateDeckHtml(copy: DeckCopy, brand: string, runId: string, variant: "ecd" | "client"): string {
  const isEcd = variant === "ecd"
  const territoryKeys = Object.keys(copy.territories)

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapeHtml(copy.titleSlide.headline)} — Pre-Production Deck (${isEcd ? "ECD Internal" : "Client"})</title>
<style>
  * { margin: 0; padding: 0; box-sizing: border-box; }
  body { font-family: system-ui, -apple-system, sans-serif; background: #0a0a0a; color: #e0e0e0; line-height: 1.6; }
  .slide { min-height: 100vh; padding: 80px 60px; display: flex; flex-direction: column; justify-content: center; border-bottom: 1px solid #1a1a1a; page-break-after: always; }
  .slide-title { background: linear-gradient(135deg, #1a1a2e 0%, #0a0a0a 100%); }
  .slide-title h1 { font-size: 3rem; font-weight: 700; margin-bottom: 16px; }
  .slide-title p { font-size: 1.25rem; color: #888; }
  .slide-section { background: #0d0d0d; }
  .slide-section h2 { font-size: 2rem; font-weight: 600; margin-bottom: 24px; color: #fff; }
  .slide-section p, .slide-section li { font-size: 1.1rem; color: #bbb; max-width: 800px; }
  .slide-territory h2 { font-size: 2.25rem; margin-bottom: 12px; }
  .risk-badge { display: inline-block; background: #7c2d12; color: #fbbf24; padding: 4px 12px; border-radius: 4px; font-size: 0.85rem; margin-top: 16px; }
  .palette-swatch { display: inline-block; width: 32px; height: 32px; border-radius: 4px; border: 1px solid #333; margin-right: 6px; vertical-align: middle; }
  .territory-options { list-style: none; padding: 0; }
  .territory-options li { padding: 16px; margin: 12px 0; border: 1px solid #333; border-radius: 8px; background: #111; }
  .territory-options li strong { color: #fff; font-size: 1.15rem; }
  .footer { text-align: center; color: #555; font-size: 0.85rem; padding: 40px; }
  .meta { color: #555; font-size: 0.8rem; margin-top: 12px; }
  @media print { .slide { page-break-after: always; min-height: auto; padding: 40px; } }
</style>
</head>
<body>

<!-- Slide 1: Title -->
<div class="slide slide-title">
  <h1>${escapeHtml(copy.titleSlide.headline)}</h1>
  <p>${escapeHtml(copy.titleSlide.subtitle.replace(/\n/g, "<br>"))}</p>
  <p class="meta">Run: ${escapeHtml(runId)} &middot; ${isEcd ? "ECD Internal Review" : "Client Review"} &middot; Generated by Greenlight</p>
</div>

<!-- Slide 2: Brief Summary -->
<div class="slide slide-section">
  <h2>Brief Summary</h2>
  <p>${escapeHtml(copy.briefSummary)}</p>
</div>

${territoryKeys.map((tid, i) => {
  const t = copy.territories[tid]
  if (!t) return ""
  return `
<!-- Territory ${i + 1} Cover -->
<div class="slide slide-territory" style="background: ${i === 0 ? '#0d1117' : i === 1 ? '#111710' : '#170f11'}">
  <h2>Territory ${i + 1}: ${escapeHtml(t.coverHeadline)}</h2>
  <p style="font-size:1.3rem;color:#ccc;margin-top:16px;">${escapeHtml(t.propositionBlurb)}</p>
  <p style="color:#888;margin-top:12px;">Tone: ${escapeHtml(t.toneDescriptor)}</p>
  ${isEcd && t.riskFlag ? `<div class="risk-badge">⚠ ${escapeHtml(t.riskFlag)}</div>` : ""}
</div>

<!-- Territory ${i + 1} Visual -->
<div class="slide slide-section">
  <h2>Visual Language — ${escapeHtml(t.coverHeadline)}</h2>
  <p>${escapeHtml(t.visualSummary)}</p>
  <p style="margin-top:16px;color:#888;">Tone: ${escapeHtml(t.toneDescriptor)}</p>
</div>

<!-- Territory ${i + 1} Details -->
<div class="slide slide-section">
  <h2>Production Notes — ${escapeHtml(t.coverHeadline)}</h2>
  <p><strong>Scene Arc:</strong> ${escapeHtml(t.sceneArcNotes)}</p>
  <p><strong>Suggested Scenes:</strong> ${t.sceneCount}</p>
  <p><strong>Flow Prompt Style:</strong> ${escapeHtml(t.flowPromptStyle)}</p>
  ${isEcd && t.riskFlag ? `<div class="risk-badge">⚠ Risk: ${escapeHtml(t.riskFlag)}</div>` : "<p style='color:#555;margin-top:12px;'>No risk flags</p>"}
</div>
`
}).join("\n")}

<!-- Visual DNA Overview -->
<div class="slide slide-section">
  <h2>Visual DNA Overview</h2>
  <p>${escapeHtml(copy.visualOverview.summary)}</p>
  <p style="margin-top:16px;"><strong>Palettes:</strong> ${escapeHtml(copy.visualOverview.paletteComparison)}</p>
  <p><strong>Cinematography:</strong> ${escapeHtml(copy.visualOverview.cinematographyComparison)}</p>
  <p><strong>Ingredients:</strong> ${escapeHtml(copy.visualOverview.ingredientComparison)}</p>
</div>

${isEcd ? `
<!-- Brand Alignment (ECD only) -->
<div class="slide slide-section" style="border-left: 3px solid #7c2d12;">
  <h2>Brand Alignment 🔒 Internal</h2>
  ${Object.entries(copy.brandAlignment.territoryNotes).map(([tid, note]) =>
    `<p style="margin-top:12px;"><strong>${escapeHtml(tid)}:</strong> ${escapeHtml(note)}</p>`
  ).join("\n")}
  <p style="margin-top:16px;"><strong>Divergence:</strong> ${escapeHtml(copy.brandAlignment.divergenceNotes)}</p>
  <p><strong>Risk Summary:</strong> ${escapeHtml(copy.brandAlignment.riskSummary)}</p>
</div>
` : ""}

<!-- Approval -->
<div class="slide slide-section">
  <h2>Approval</h2>
  <p>${escapeHtml(copy.approvalSlide.instructions)}</p>
  <ul class="territory-options">
    ${copy.approvalSlide.territoryOptions.map(opt => `
      <li>
        <strong>${escapeHtml(opt.name)}</strong> (${escapeHtml(opt.id)})
        <p style="color:#888;margin-top:4px;">${escapeHtml(opt.summary)}</p>
      </li>
    `).join("\n")}
  </ul>
</div>

<!-- Next Steps -->
<div class="slide slide-section">
  <h2>Next Steps</h2>
  <p>${escapeHtml(copy.nextSteps)}</p>
</div>

<div class="footer">
  <p>Greenlight v0.1 &middot; ${escapeHtml(brand)} &middot; ${isEcd ? "ECD Internal Deck" : "Client Deck"}</p>
</div>

</body>
</html>`
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
}
