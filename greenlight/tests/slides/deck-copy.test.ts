// ── Validation helpers (mirrors expected implementation) ────────────────────────

function validateDeckCopy(copy: unknown): { valid: boolean; gaps: string[] } {
  const gaps: string[] = []

  if (typeof copy !== "object" || copy === null) {
    return { valid: false, gaps: ["Response is not an object"] }
  }

  const c = copy as Record<string, unknown>

  // Title slide
  if (typeof c["titleSlide"] !== "object" || c["titleSlide"] === null) {
    gaps.push("titleSlide is missing")
  } else {
    const ts = c["titleSlide"] as Record<string, unknown>
    if (typeof ts["headline"] !== "string" || !ts["headline"]) gaps.push("titleSlide.headline")
    if (typeof ts["subtitle"] !== "string" || !ts["subtitle"]) gaps.push("titleSlide.subtitle")
  }

  // Brief summary
  if (typeof c["briefSummary"] !== "string" || !c["briefSummary"]) {
    gaps.push("briefSummary is missing")
  }

  // Territories (must have exactly 3)
  if (typeof c["territories"] !== "object" || c["territories"] === null) {
    gaps.push("territories is missing")
  } else {
    const territories = c["territories"] as Record<string, unknown>
    const keys = Object.keys(territories)
    if (keys.length < 3) gaps.push(`Expected 3 territories, got ${keys.length}`)

    for (const key of keys) {
      const t = territories[key] as Record<string, unknown> | null
      if (!t || typeof t !== "object") {
        gaps.push(`territories.${key} is not an object`)
        continue
      }
      const required = [
        "coverHeadline",
        "propositionBlurb",
        "visualSummary",
        "toneDescriptor",
        "sceneArcNotes",
        "flowPromptStyle",
      ]
      for (const field of required) {
        if (typeof t[field] !== "string" || !t[field]) {
          gaps.push(`territories.${key}.${field} is missing`)
        }
      }
      if (typeof t["sceneCount"] !== "number" || (t["sceneCount"] as number) < 1) {
        gaps.push(`territories.${key}.sceneCount must be positive`)
      }
    }
  }

  // Visual overview
  if (typeof c["visualOverview"] !== "object" || c["visualOverview"] === null) {
    gaps.push("visualOverview is missing")
  } else {
    const vo = c["visualOverview"] as Record<string, unknown>
    for (const field of ["summary", "paletteComparison", "cinematographyComparison"]) {
      if (typeof vo[field] !== "string" || !vo[field]) {
        gaps.push(`visualOverview.${field} is missing`)
      }
    }
  }

  // Brand alignment (ECD-only — can be empty for client)
  if (typeof c["brandAlignment"] !== "object" || c["brandAlignment"] === null) {
    gaps.push("brandAlignment is missing")
  }

  // Approval slide
  if (typeof c["approvalSlide"] !== "object" || c["approvalSlide"] === null) {
    gaps.push("approvalSlide is missing")
  } else {
    const as = c["approvalSlide"] as Record<string, unknown>
    if (typeof as["instructions"] !== "string" || !as["instructions"]) {
      gaps.push("approvalSlide.instructions is missing")
    }
    if (!Array.isArray(as["territoryOptions"]) || (as["territoryOptions"] as unknown[]).length < 3) {
      gaps.push("approvalSlide.territoryOptions needs 3 entries")
    }
  }

  // Next steps
  if (typeof c["nextSteps"] !== "string" || !c["nextSteps"]) {
    gaps.push("nextSteps is missing")
  }

  return { valid: gaps.length === 0, gaps }
}

